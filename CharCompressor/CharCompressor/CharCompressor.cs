        private void analyzeButton_Click(object sender, EventArgs e)
        {
            // For every second byte in bigNumbers[]
            for (int index = 0; index < 2000; index += 2)
            {
                bool foundBytePair = false;
                int bytePairsIndex = 0;
                // Search through bytePairs until we find the byte pair
                while (bytePairs[bytePairsIndex] != null && bytePairsIndex < 2000)
                {
                    // if we find the byte pair already in bytePairs[][], increment the count
                    if (bytePairs[bytePairsIndex][0] == bigNumbers[index] && bytePairs[bytePairsIndex][1] == bigNumbers[index + 1])
                    {
                        foundBytePair = true;
                        bytePairs[bytePairsIndex][2] += 1;
                        break;
                    }
                    bytePairsIndex++;
                }
                // if the byte pair was not found, add it to bytePairs[][]
                if (!foundBytePair)
                {
                    bytePairs[bytePairsIndex] = new byte[3];
                    bytePairs[bytePairsIndex][0] = bigNumbers[index];
                    bytePairs[bytePairsIndex][1] = bigNumbers[index + 1];
                    bytePairs[bytePairsIndex][2] = 1;
                }
            }

            
            // print out a header
            outputBox.Text += "Byte Pair\t\tCount\r\n\r\n";

            // iterate through the found byte pairs and print them to the textbox
            int i = 0;
            while (bytePairs[i] != null && i < 2000)
            {
                outputBox.Text += Extensions.TextBoxExtension.toHex(bytePairs[i]);
                outputBox.Text = outputBox.Text.Remove(outputBox.Text.Length - 6, 6);
                outputBox.Text += "\t" + bytePairs[i][2].ToString() + "\r\n";
                i++;
            }

            // count up the total found bytes and total byte pairs
            i = 0;
            int byteCount = 0;
            while (bytePairs[i] != null && i < 2000)
            {
                byteCount += bytePairs[i][2];
                i++;
            }
            bytePairCount = i;
            outputBox.Text += "\r\n" + "total number of byte pairs counted: " + byteCount.ToString();
            outputBox.Text += "\r\n" + "total number of different byte pairs: " + bytePairCount.ToString();


            /* analyze the smallNumbers[] array */
            for (int index = 0; index < 900; index += 2)
            {
                bool foundBytePair = false;
                int bytePairsIndex = 0;
                // Search through bytePairs until we find the byte pair
                while (bytePairs[bytePairsIndex] != null && bytePairsIndex < 2000)
                {
                    // if we find the byte pair already in bytePairs[][], increment the count
                    if (bytePairs[bytePairsIndex][0] == smallNumbers[index] && bytePairs[bytePairsIndex][1] == smallNumbers[index + 1])
                    {
                        foundBytePair = true;
                        bytePairs[bytePairsIndex][2] += 1;
                        break;
                    }
                    bytePairsIndex++;
                }
                // if the byte pair was not found, add it to bytePairs[][]
                if (!foundBytePair)
                {
                    // two bytes to remember the byte pair and one byte to remember how many times we've found it
                    bytePairs[bytePairsIndex] = new byte[3];
                    // remember the byte pair for the compression table later
                    bytePairs[bytePairsIndex][0] = smallNumbers[index];
                    bytePairs[bytePairsIndex][1] = smallNumbers[index + 1];
                    // we have found one example of this new byte pair so increase the count by 1
                    bytePairs[bytePairsIndex][2] = 1;
                }
            }

            // print out a header
            outputBox.Text += "\r\n\r\nByte Pair\t\tCount\r\n\r\n";

            // iterate through the found byte pairs and print them to the textbox
            i = 0;
            while (bytePairs[i] != null && i < 2000)
            {
                outputBox.Text += Extensions.TextBoxExtension.toHex(bytePairs[i]);
                outputBox.Text = outputBox.Text.Remove(outputBox.Text.Length - 6, 6);
                outputBox.Text += "\t" + bytePairs[i][2].ToString() + "\r\n";
                i++;
            }

            // count up the total found bytes and total byte pairs
            i = 0;
            byteCount = 0;
            while (bytePairs[i] != null && i < 2000)
            {
                byteCount += bytePairs[i][2];
                i++;
            }
            bytePairCount = i;
            outputBox.Text += "\r\n" + "total number of byte pairs counted: " + byteCount.ToString();
            outputBox.Text += "\r\n" + "total number of different byte pairs: " + bytePairCount.ToString();

            generateCompressionTable();
            generateCompressedArrays();
        }

