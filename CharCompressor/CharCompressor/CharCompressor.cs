        private void generateCompressedArrays()
        {
            compressedArrayBox.Text += "Compressed Arrays:\r\n";
            compressedArrayBox.Text += "char bigNumbers[10][100] = {\r\n{";

            int byteCount = 0;
            // search through bigNumbers[] byte pairs and find the corresponding bytePairs[] index and print it
            for (int index = 0; index < 2000; index += 2)
            {
                int i = 0;
                byteCount++;
                // search through bytePairs to find which entry corresponds to the current byte pair
                while (bytePairs[i] != null && i < 1000)
                {
                    if (bytePairs[i][0] == bigNumbers[index] && bytePairs[i][1] == bigNumbers[index + 1])
                    {
                        break;
                    }
                    i++;
                }
                // print out the index (in byte form) which corresponds to the current byte pair in bytePairs[]
                compressedArrayBox.Text += Extensions.TextBoxExtension.toHex(Convert.ToByte(i));
                // we want each line to contain 10 bytes for readability
                if (byteCount % 10 == 0 && index > 0)
                {
                    compressedArrayBox.Text += "\r\n";
                }
                // each LCD number in bigNumbers is 100 bytes long so close the array and move on to the next until all bigNumbers have been accounted for 
                if (byteCount % 100 == 0 && index > 0)
                {
                    compressedArrayBox.Text = compressedArrayBox.Text.Remove(compressedArrayBox.Text.Length - 3, 3);
                    compressedArrayBox.Text += " },\r\n\r\n{";
                }
            }
            compressedArrayBox.Text = compressedArrayBox.Text.Remove(compressedArrayBox.Text.Length - 6, 6);
            compressedArrayBox.Text += " };";

            compressedArrayBox.Text += "\r\n\r\nchar smallNumbers[10][45] = {\r\n{";

            byteCount = 0;
            // search through smallNumbers[] byte pairs and find the corresponding bytePairs[] index and print it
            for (int index = 0; index < 900; index += 2)
            {
                int i = 0;
                byteCount++;
                // search through bytePairs to find which entry corresponds to the current byte pair
                while (bytePairs[i] != null && i < 1000)
                {
                    if (bytePairs[i][0] == smallNumbers[index] && bytePairs[i][1] == smallNumbers[index + 1])
                    {
                        break;
                    }
                    i++;
                }
                compressedArrayBox.Text += Extensions.TextBoxExtension.toHex(Convert.ToByte(i));
                if (byteCount % 5 == 0 && index > 0)
                {
                    compressedArrayBox.Text += "\r\n";
                }
                if (byteCount % 45 == 0 && index > 0)
                {
                    compressedArrayBox.Text = compressedArrayBox.Text.Remove(compressedArrayBox.Text.Length - 3, 3);
                    compressedArrayBox.Text += " },\r\n\r\n{";
                }
            }
            compressedArrayBox.Text = compressedArrayBox.Text.Remove(compressedArrayBox.Text.Length - 6, 6);
            compressedArrayBox.Text += " };";
        }
